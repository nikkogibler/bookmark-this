def validate(root: Path, config: dict[str, Any]) -> int:
    errors: list[str] = []
    warnings: list[str] = []
    paths = config["paths"]
    expected_dirs = [root / paths[name] for name in ("bookmarks", "views", "collections")]
    for directory in expected_dirs:
        if not directory.is_dir():
            errors.append(f"Missing directory: {directory}")
    index_path = root / paths["index"]
    if not index_path.is_file():
        errors.append(f"Missing index: {index_path}")
    elif index_path.read_text(encoding="utf-8").splitlines()[:1] != [MARKER]:
        warnings.append(f"Index is not generated: {index_path}")
    visualizer_config = config.get("visualizer", {"enabled": False})
    if visualizer_config.get("enabled", False):
        visualizer_path = root / visualizer_config.get("path", "visualizer/index.html")
        if not visualizer_path.is_file():
            errors.append(f"Missing enabled visualizer: {visualizer_path}")

    configured_categories = {category["slug"] for category in config["categories"]}
    seen_urls: dict[str, Path] = {}
    try:
        records = bookmark_records(root, config)
    except SystemError as exc:
        errors.append(str(exc))
        records = []

    for record in records:
        path = record["path"]
        metadata = record["metadata"]
        missing = sorted(REQUIRED_FIELDS - metadata.keys())
        if missing:
            errors.append(f"{path}: missing {', '.join(missing)}")
        if metadata.get("type") != "web-bookmark":
            errors.append(f"{path}: type must be web-bookmark")
        if metadata.get("status") != "bookmarked":
            errors.append(f"{path}: status must be bookmarked")
        if metadata.get("captured") and not DATE_RE.fullmatch(str(metadata["captured"])):
            errors.append(f"{path}: captured must be YYYY-MM-DD")
        for field in ("tags", "categories"):
            values = metadata.get(field)
            if not isinstance(values, list) or not values:
                errors.append(f"{path}: {field} must be a non-empty list")
            elif any(not SLUG_RE.fullmatch(str(value)) for value in values):
                errors.append(f"{path}: {field} contains a non-slug value")
        for category in metadata.get("categories", []) if isinstance(metadata.get("categories"), list) else []:
            if category not in configured_categories:
                errors.append(f"{path}: unknown category {category!r}")
        for field in ("url", "canonical_url", "original_url"):
            value = metadata.get(field)
            if not value:
                continue
            normalized = str(value).rstrip("/")
            if normalized in seen_urls and seen_urls[normalized] != path:
                errors.append(f"Duplicate {field} in {seen_urls[normalized]} and {path}")
            else:
                seen_urls[normalized] = path
        tags = metadata.get("tags", [])
        if isinstance(tags, list) and not 3 <= len(tags) <= 8:
            warnings.append(f"{path}: expected 3–8 tags, found {len(tags)}")

    for warning in warnings:
        print(f"WARNING: {warning}")
    for error in errors:
        print(f"ERROR: {error}", file=sys.stderr)
    if errors:
        print(f"Validation failed with {len(errors)} error(s) and {len(warnings)} warning(s).", file=sys.stderr)
        return 1
    print(f"Validation passed for {len(records)} bookmark(s) with {len(warnings)} warning(s).")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("rebuild", "visualize", "validate"))
    parser.add_argument("root", type=Path, help="Bookmark-system root directory")
    args = parser.parse_args()
    root = args.root.expanduser().resolve()
    try:
        config = load_config(root)
        if args.command == "rebuild":
            rebuild(root, config)
            return 0
        if args.command == "visualize":
            visualize(root, config)
            return 0
        return validate(root, config)
    except SystemError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
