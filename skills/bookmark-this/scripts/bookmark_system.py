#!/usr/bin/env python3
"""Rebuild and validate a bookmark-this Markdown hierarchy using stdlib only."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any


MARKER = "<!-- generated by bookmark-this; do not edit -->"
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
REQUIRED_FIELDS = {
    "title",
    "type",
    "url",
    "canonical_url",
    "domain",
    "captured",
    "tags",
    "categories",
    "status",
}


class SystemError(Exception):
    pass


def load_config(root: Path) -> dict[str, Any]:
    path = root / ".bookmark-system" / "config.json"
    if not path.is_file():
        raise SystemError(f"Missing configuration: {path}")
    try:
        config = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemError(f"Cannot read valid JSON configuration: {exc}") from exc

    if config.get("version") != 1:
        raise SystemError("config.json must contain version 1")
    for key in ("paths", "categories", "capture", "navigation"):
        if key not in config:
            raise SystemError(f"config.json is missing {key!r}")

    paths = config["paths"]
    for key in ("bookmarks", "views", "collections", "index"):
        value = paths.get(key)
        if not isinstance(value, str) or not value.strip():
            raise SystemError(f"paths.{key} must be a non-empty relative path")
        candidate = Path(value)
        if candidate.is_absolute() or ".." in candidate.parts:
            raise SystemError(f"paths.{key} must stay inside the bookmark root")

    category_slugs: set[str] = set()
    for category in config["categories"]:
        if not isinstance(category, dict):
            raise SystemError("Each category must be an object")
        slug = category.get("slug", "")
        if not isinstance(slug, str) or not SLUG_RE.fullmatch(slug):
            raise SystemError(f"Invalid category slug: {slug!r}")
        if slug in category_slugs:
            raise SystemError(f"Duplicate category slug: {slug}")
        category_slugs.add(slug)
        if not category.get("label"):
            raise SystemError(f"Category {slug!r} needs a label")

    if config.get("link_style", "markdown") not in {"markdown", "wikilink"}:
        raise SystemError("link_style must be 'markdown' or 'wikilink'")
    visualizer = config.get("visualizer", {"enabled": False, "path": "visualizer/index.html"})
    if not isinstance(visualizer, dict) or not isinstance(visualizer.get("enabled", False), bool):
        raise SystemError("visualizer must contain a boolean enabled value")
    visualizer_path = Path(str(visualizer.get("path", "visualizer/index.html")))
    if visualizer_path.is_absolute() or ".." in visualizer_path.parts or visualizer_path.suffix.lower() != ".html":
        raise SystemError("visualizer.path must be a relative .html path inside the root")
    return config


def parse_scalar(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
        return value[1:-1]
    return value


def parse_frontmatter(path: Path) -> dict[str, Any]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise SystemError(f"Cannot read {path}: {exc}") from exc
    if not lines or lines[0].strip() != "---":
        raise SystemError(f"Missing YAML frontmatter in {path}")

    data: dict[str, Any] = {}
    current_list: str | None = None
    for line in lines[1:]:
        if line.strip() == "---":
            return data
        list_match = re.match(r"^\s+-\s+(.+?)\s*$", line)
        if list_match and current_list:
            data[current_list].append(parse_scalar(list_match.group(1)))
            continue
        field_match = re.match(r"^([A-Za-z_][A-Za-z0-9_-]*):(?:\s*(.*))?$", line)
        if not field_match:
            if line.strip() and not line.lstrip().startswith("#"):
                current_list = None
            continue
        key, raw_value = field_match.group(1), field_match.group(2) or ""
        if raw_value.strip():
            data[key] = parse_scalar(raw_value)
            current_list = None
        else:
            data[key] = []
            current_list = key
    raise SystemError(f"Unclosed YAML frontmatter in {path}")


def bookmark_records(root: Path, config: dict[str, Any]) -> list[dict[str, Any]]:
    directory = root / config["paths"]["bookmarks"]
    if not directory.exists():
        return []
    records: list[dict[str, Any]] = []
    for path in sorted(directory.rglob("*.md")):
        metadata = parse_frontmatter(path)
        records.append({"path": path, "metadata": metadata})
    return records


def relative_link(root: Path, source: Path, target: Path, title: str, style: str) -> str:
    if style == "wikilink":
        target_from_root = target.relative_to(root).with_suffix("").as_posix()
        return f"[[{target_from_root}|{title}]]"
    relative = os.path.relpath(target, start=source.parent).replace(os.sep, "/")
    return f"[{title}]({relative})"


def bookmark_line(root: Path, source: Path, record: dict[str, Any], style: str) -> str:
    metadata = record["metadata"]
    title = str(metadata.get("title") or record["path"].stem)
    domain = str(metadata.get("domain") or "unknown domain")
    captured = str(metadata.get("captured") or "unknown date")
    link = relative_link(root, source, record["path"], title, style)
    return f"- {link} — {domain} · {captured}"


def write_generated(path: Path, body: str) -> None:
    if path.exists():
        first_line = path.read_text(encoding="utf-8").splitlines()[:1]
        if first_line != [MARKER]:
            raise SystemError(f"Refusing to overwrite unmarked file: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{MARKER}\n\n{body.rstrip()}\n", encoding="utf-8")


def rebuild(root: Path, config: dict[str, Any]) -> None:
    paths = config["paths"]
    bookmarks_dir = root / paths["bookmarks"]
    views_dir = root / paths["views"]
    collections_dir = root / paths["collections"]
    index_path = root / paths["index"]
    for directory in (bookmarks_dir, views_dir / "categories", views_dir / "tags", collections_dir):
        directory.mkdir(parents=True, exist_ok=True)

    records = bookmark_records(root, config)
    style = config.get("link_style", "markdown")
    by_category: dict[str, list[dict[str, Any]]] = defaultdict(list)
    by_tag: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        metadata = record["metadata"]
        for category in metadata.get("categories", []) if isinstance(metadata.get("categories"), list) else []:
            by_category[str(category)].append(record)
        for tag in metadata.get("tags", []) if isinstance(metadata.get("tags"), list) else []:
            by_tag[str(tag)].append(record)

    categories = config["categories"]
    index_lines = ["# Bookmark index", "", f"{len(records)} saved bookmark{'s' if len(records) != 1 else ''}.", "", "## Browse by category", ""]
    for category in categories:
        slug = category["slug"]
        view_path = views_dir / "categories" / f"{slug}.md"
        link = relative_link(root, index_path, view_path, category["label"], style)
        index_lines.append(f"- {link} ({len(by_category.get(slug, []))}) — {category.get('description', '').strip()}")

    if config["navigation"].get("generate_tag_views", True) and by_tag:
        index_lines.extend(["", "## Browse by tag", ""])
        for tag in sorted(by_tag):
            view_path = views_dir / "tags" / f"{tag}.md"
            link = relative_link(root, index_path, view_path, tag, style)
            index_lines.append(f"- {link} ({len(by_tag[tag])})")

    index_lines.extend(["", "## All bookmarks", ""])
    ordered = sorted(records, key=lambda item: (str(item["metadata"].get("captured", "")), str(item["metadata"].get("title", ""))), reverse=True)
    index_lines.extend(bookmark_line(root, index_path, record, style) for record in ordered)
    if not records:
        index_lines.append("No bookmarks yet.")
    write_generated(index_path, "\n".join(index_lines))

    if config["navigation"].get("generate_category_views", True):
        for category in categories:
            slug = category["slug"]
            view_path = views_dir / "categories" / f"{slug}.md"
            lines = [f"# {category['label']}", "", category.get("description", "").strip(), ""]
            selected = sorted(by_category.get(slug, []), key=lambda item: str(item["metadata"].get("title", "")).lower())
            lines.extend(bookmark_line(root, view_path, record, style) for record in selected)
            if not selected:
                lines.append("No bookmarks in this category yet.")
            write_generated(view_path, "\n".join(lines))

    if config["navigation"].get("generate_tag_views", True):
        for tag, selected in sorted(by_tag.items()):
            if not SLUG_RE.fullmatch(tag):
                continue
            view_path = views_dir / "tags" / f"{tag}.md"
            lines = [f"# {tag}", ""]
            for record in sorted(selected, key=lambda item: str(item["metadata"].get("title", "")).lower()):
                lines.append(bookmark_line(root, view_path, record, style))
            write_generated(view_path, "\n".join(lines))

    print(f"Rebuilt navigation for {len(records)} bookmark(s): {index_path}")


def note_summary(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"^## What it is\s*\n+(.*?)(?=\n## |\Z)", text, flags=re.MULTILINE | re.DOTALL)
    if not match:
        return ""
    paragraph = re.split(r"\n\s*\n", match.group(1).strip(), maxsplit=1)[0]
    return re.sub(r"\s+", " ", paragraph).strip()[:280]


